// Package web implements the Flaggo Control Plane Frontend: a management
// dashboard for feature flags plus an API gateway that fronts the Control
// Plane Backend API.
//
// Why one service instead of a static site plus a separate proxy?
//
//   - The stack stays "4 apps": frontend, api, client, database.
//   - Only the frontend needs a host-published port, so all backend traffic
//     (including the internal /api path) is confined to the private network.
//   - The dashboard ships as a single static binary: no node_modules, no
//     asset build pipeline, no extra base image to patch.
package web

import (
	"embed"
	"encoding/json"
	"errors"
	"io/fs"
	"log/slog"
	"net/http"
	"net/http/httputil"
	"net/url"
	"strings"
	"time"

	"github.com/xarop-pa-toss/flaggo/internal/http/middleware"
	"github.com/xarop-pa-toss/flaggo/internal/observability"
)

var (
	errNoBackend       = errors.New("backend URL is required")
	errBackendNotReady = errors.New("backend is not ready")
)

//go:embed ui
var uiFS embed.FS

// Deps holds dependencies for the frontend/gateway.
type Deps struct {
	// BackendURL is the base URL of the Control Plane Backend API,
	// e.g. http://api:8080 inside the container network.
	BackendURL string
	Logger     *slog.Logger
	Metrics    *observability.Metrics
	// ReadyTimeout bounds the backend readiness probe.
	ReadyTimeout time.Duration
}

// NewHandler builds the frontend HTTP handler.
func NewHandler(d Deps) (http.Handler, error) {
	if d.BackendURL == "" {
		return nil, errNoBackend
	}
	target, err := url.Parse(d.BackendURL)
	if err != nil {
		return nil, err
	}
	if d.ReadyTimeout == 0 {
		d.ReadyTimeout = 2 * time.Second
	}

	mux := http.NewServeMux()
	mux.Handle("/api/", newProxy(target, d.Logger))
	mux.Handle("GET /static/", staticHandler())
	mux.HandleFunc("GET /healthz", func(w http.ResponseWriter, r *http.Request) {
		writeJSON(w, http.StatusOK, map[string]string{"status": "ok"})
	})
	mux.HandleFunc("GET /readyz", func(w http.ResponseWriter, r *http.Request) {
		if err := probe(target, "/readyz", d.ReadyTimeout); err != nil {
			writeJSON(w, http.StatusServiceUnavailable, map[string]string{
				"status": "not ready",
				"reason": err.Error(),
			})
			return
		}
		writeJSON(w, http.StatusOK, map[string]string{"status": "ready"})
	})
	mux.Handle("GET /metrics", observability.Handler())
	mux.Handle("/", indexHandler())

	var h http.Handler = mux
	h = middleware.Metrics(d.Metrics)(h)
	h = middleware.Logging(d.Logger)(h)
	h = middleware.Recovery(d.Logger)(h)
	h = middleware.RequestID(h)
	return h, nil
}

// newProxy forwards /api/<path> to the backend's /<path>.
//
// The request id generated by the gateway is propagated to the backend so a
// single id correlates a dashboard click with the backend logs and metrics.
func newProxy(target *url.URL, log *slog.Logger) http.Handler {
	proxy := httputil.NewSingleHostReverseProxy(target)
	inner := proxy.Director
	proxy.Director = func(r *http.Request) {
		inner(r)
		r.URL.Path = strings.TrimPrefix(r.URL.Path, "/api")
		if r.URL.RawPath != "" {
			r.URL.RawPath = strings.TrimPrefix(r.URL.RawPath, "/api")
		}
		if id := middleware.RequestIDFromContext(r.Context()); id != "" {
			r.Header.Set("X-Request-ID", id)
		}
	}
	proxy.ErrorHandler = func(w http.ResponseWriter, r *http.Request, err error) {
		log.Error("backend unreachable", "err", err, "path", r.URL.Path)
		writeJSON(w, http.StatusBadGateway, map[string]string{
			"error": "control plane backend unreachable",
		})
	}
	// The backend echoes the request id it received. The gateway already set
	// the same id on the response, so drop the backend's copy to avoid
	// emitting the header twice.
	proxy.ModifyResponse = func(resp *http.Response) error {
		resp.Header.Del("X-Request-ID")
		return nil
	}
	return proxy
}

// staticHandler serves the embedded dashboard assets under /static/.
func staticHandler() http.Handler {
	sub, err := fs.Sub(uiFS, "ui")
	if err != nil {
		panic(err)
	}
	return http.StripPrefix("/static/", http.FileServer(http.FS(sub)))
}

// indexHandler serves the dashboard shell.
func indexHandler() http.Handler {
	data, err := uiFS.ReadFile("ui/index.html")
	if err != nil {
		panic(err)
	}
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if r.Method != http.MethodGet && r.Method != http.MethodHead {
			w.Header().Set("Allow", "GET, HEAD")
			http.Error(w, "method not allowed", http.StatusMethodNotAllowed)
			return
		}
		w.Header().Set("Content-Type", "text/html; charset=utf-8")
		w.Header().Set("Cache-Control", "no-store")
		_, _ = w.Write(data)
	})
}

// probe checks that the backend is reachable and ready.
func probe(target *url.URL, path string, timeout time.Duration) error {
	u := *target
	u.Path = path
	client := &http.Client{Timeout: timeout}
	resp, err := client.Get(u.String())
	if err != nil {
		return err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return errBackendNotReady
	}
	return nil
}

func writeJSON(w http.ResponseWriter, code int, v any) {
	w.Header().Set("Content-Type", "application/json")
	w.WriteHeader(code)
	_ = json.NewEncoder(w).Encode(v)
}
